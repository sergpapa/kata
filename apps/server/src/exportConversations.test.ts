import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { openDatabase, type Db } from './modules/lifecycle/database.js';
import { removeDir } from './modules/content/testkit/releaseFixture.js';
import {
  appendTurn,
  clearConversation,
  startConversation,
  type TurnProvenance,
} from './modules/feedback/feedbackRepository.js';
import {
  exportApp,
  exportFile,
  LESSON_3,
  saveAll,
  STANDARD_ACTIVITIES,
  WHOLE_COURSE,
  writeExportRelease,
} from './modules/export/testkit/exportFixture.js';
import {
  blockWith,
  fencedBlocks,
  linesOutsideFences,
  section,
} from './modules/export/testkit/markdownReaders.js';

/**
 * Criteria EX9–EX11, EX13 and EX14 in docs/specs/export.md (ADR 0020): whether Claude's feedback
 * travels, and what the export refuses.
 *
 * Conversations are arranged straight into the store with the feedback repository rather than run
 * through a fake Claude: what is under test is what the export reads, and the store is what it
 * reads. Every "absent" claim is paired with the same store exported with conversations on, so an
 * export that never shows conversations at all cannot pass the absence tests.
 */

const dirs: string[] = [];
let db: Db;

beforeEach(() => {
  db = openDatabase(':memory:');
  vi.useFakeTimers({ toFake: ['Date'] });
  vi.setSystemTime(new Date('2026-11-19T09:00:00.000Z'));
});

afterEach(() => {
  vi.useRealTimers();
  db.close();
  while (dirs.length > 0) removeDir(dirs.pop() as string);
});

function release(options: Parameters<typeof writeExportRelease>[0] = {}): string {
  const dir = writeExportRelease(options);
  dirs.push(dir);
  return dir;
}

function app(dir = release()) {
  return exportApp(db, [{ id: 'FIX', dir }]);
}

const WITH = { ...WHOLE_COURSE, conversations: '1' };
const LABEL = 'AI feedback (generated by Claude, not a review by the author)';

const lesson1: TurnProvenance = {
  candidateLessonId: 'FIX-LS-01',
  contentVersion: '1.0.0-draft',
  releaseId: 'FIX-RELEASE',
};
const lesson3: TurnProvenance = { ...lesson1, candidateLessonId: LESSON_3 };

/** A finished exchange and a follow-up whose reply failed part-way, on ACT-1-ZULU. */
function zuluConversation(): void {
  const { conversationId } = startConversation(db, {
    activityId: 'ACT-1-ZULU',
    sessionId: 'session-zulu',
    sentFields: [
      { fieldName: 'prediction', text: 'Sent prediction text.' },
      { fieldName: 'observation', text: 'Sent observation text.' },
    ],
    provenance: lesson1,
    at: '2026-11-19T09:10:00.000Z',
  });
  appendTurn(db, conversationId, {
    role: 'claude',
    text: 'A reply from Claude about the prediction.',
    model: 'claude-sonnet-5-5',
    outcome: 'complete',
    provenance: lesson1,
    at: '2026-11-19T09:10:20.000Z',
  });
  appendTurn(db, conversationId, {
    role: 'learner',
    text: 'A follow-up question from the owner.',
    provenance: lesson1,
    at: '2026-11-19T09:11:00.000Z',
  });
  appendTurn(db, conversationId, {
    role: 'claude',
    text: 'A partial reply',
    model: null,
    outcome: 'failed',
    failure: 'Claude Code stopped before it finished.',
    provenance: lesson1,
    at: '2026-11-19T09:11:30.000Z',
  });
}

describe('without conversations (EX9)', () => {
  it('carries no turn, failure or model when conversations are off or not asked for', async () => {
    const server = app();
    zuluConversation();

    const withThem = await exportFile(server, WITH);
    const off = await exportFile(server, { ...WHOLE_COURSE, conversations: '0' });
    const unasked = await exportFile(server, WHOLE_COURSE);

    const turnTexts = [
      'Sent prediction text.',
      'Sent observation text.',
      'A reply from Claude about the prediction.',
      'A follow-up question from the owner.',
      'A partial reply',
      'Claude Code stopped before it finished.',
      'claude-sonnet-5-5',
      LABEL,
    ];
    for (const text of turnTexts) expect(withThem, text).toContain(text);
    for (const file of [off, unasked]) {
      for (const text of turnTexts) expect(file, text).not.toContain(text);
    }
  });
});

describe('with conversations (EX10)', () => {
  async function exported(): Promise<string> {
    const server = app();
    zuluConversation();
    return exportFile(server, WITH);
  }

  it('puts the conversation after its own activity’s fields, labelled as AI feedback', async () => {
    const file = await exported();

    const zulu = section(file, 'ACT-1-ZULU', 3);
    const headings = linesOutsideFences(zulu).filter((line) => line.startsWith('#### '));
    expect(headings).toEqual(['#### Your prediction', '#### What you observed', `#### ${LABEL}`]);
    expect(section(file, 'ACT-1-ALPHA', 3)).not.toContain(LABEL);
  });

  it('gives the first turn its line and each sent field its own block, under its label', async () => {
    const file = await exported();

    const outside = linesOutsideFences(file);
    expect(outside).toContain('Turn 1 · You · 2026-11-19T09:10:00.000Z');
    expect(blockWith(file, 'Sent prediction text.').description).toContain('Your prediction');
    expect(blockWith(file, 'Sent observation text.').description).toContain('What you observed');
  });

  it('gives a learner turn with no text of its own no block of its own', async () => {
    const file = await exported();

    const turnOne = fencedBlocks(file).filter((block) => block.description.startsWith('Turn 1 '));
    expect(turnOne).toHaveLength(0);
    expect(fencedBlocks(file).filter((block) => block.content === '')).toHaveLength(0);
  });

  it('describes each reply by number, model and time, and each follow-up by number and time', async () => {
    const file = await exported();

    expect(blockWith(file, 'A reply from Claude about the prediction.').description).toBe(
      'Turn 2 · Claude · claude-sonnet-5-5 · 2026-11-19T09:10:20.000Z',
    );
    expect(blockWith(file, 'A follow-up question from the owner.').description).toBe(
      'Turn 3 · You · 2026-11-19T09:11:00.000Z',
    );
  });

  it('lists the turns in the order they were taken', async () => {
    const file = await exported();

    const turns = linesOutsideFences(section(file, 'ACT-1-ZULU', 3))
      .filter((line) => line.startsWith('Turn '))
      .map((line) => line.split(' · ')[0]);
    expect(turns).toEqual(['Turn 1', 'Turn 2', 'Turn 3', 'Turn 4']);
  });

  it('marks a failed reply with its failure, keeping what had arrived', async () => {
    const file = await exported();

    expect(blockWith(file, 'A partial reply').description).toBe(
      'Turn 4 · Claude · model not reported · 2026-11-19T09:11:30.000Z · Failed: Claude Code stopped before it finished.',
    );
  });

  it('keeps the line of a failed reply that sent nothing, and gives it no block', async () => {
    const server = app();
    const { conversationId } = startConversation(db, {
      activityId: 'ACT-3-ONLY',
      sessionId: 'session-empty',
      sentFields: [{ fieldName: 'prediction', text: 'Sent before a failure.' }],
      provenance: lesson3,
      at: '2026-11-19T09:20:00.000Z',
    });
    appendTurn(db, conversationId, {
      role: 'claude',
      text: '',
      model: null,
      outcome: 'failed',
      failure: 'Claude Code was not found.',
      provenance: lesson3,
      at: '2026-11-19T09:20:05.000Z',
    });

    const file = await exportFile(server, WITH);

    const line =
      'Turn 2 · Claude · model not reported · 2026-11-19T09:20:05.000Z · Failed: Claude Code was not found.';
    expect(linesOutsideFences(file)).toContain(line);
    expect(fencedBlocks(file).filter((block) => block.description === line)).toHaveLength(0);
    expect(fencedBlocks(file).filter((block) => block.content === '')).toHaveLength(0);
  });

  it('says model not reported for a finished reply whose model the store lacks', async () => {
    const server = app();
    const { conversationId } = startConversation(db, {
      activityId: 'ACT-3-ONLY',
      sessionId: 'session-no-model',
      sentFields: [{ fieldName: 'prediction', text: 'Sent for a reply.' }],
      provenance: lesson3,
      at: '2026-11-19T09:30:00.000Z',
    });
    appendTurn(db, conversationId, {
      role: 'claude',
      text: 'A finished reply with no model.',
      model: null,
      outcome: 'complete',
      provenance: lesson3,
      at: '2026-11-19T09:30:10.000Z',
    });

    const file = await exportFile(server, WITH);

    expect(blockWith(file, 'A finished reply with no model.').description).toBe(
      'Turn 2 · Claude · model not reported · 2026-11-19T09:30:10.000Z',
    );
  });
});

describe('hidden conversations (EX11)', () => {
  it('never carries a conversation Start over hid, and carries the one that replaced it', async () => {
    const server = app();
    const hidden = startConversation(db, {
      activityId: 'ACT-1-ZULU',
      sessionId: 'session-hidden',
      sentFields: [{ fieldName: 'prediction', text: 'Sent before Start over.' }],
      provenance: lesson1,
      at: '2026-11-19T09:05:00.000Z',
    });
    appendTurn(db, hidden.conversationId, {
      role: 'claude',
      text: 'A reply the owner hid.',
      model: 'claude-sonnet-5-5',
      outcome: 'complete',
      provenance: lesson1,
      at: '2026-11-19T09:05:20.000Z',
    });
    clearConversation(db, hidden.conversationId, '2026-11-19T09:06:00.000Z');
    zuluConversation();

    const onlyHidden = startConversation(db, {
      activityId: 'ACT-3-ONLY',
      sessionId: 'session-lesson-3',
      sentFields: [{ fieldName: 'prediction', text: 'Sent from lesson 3.' }],
      provenance: lesson3,
      at: '2026-11-19T09:07:00.000Z',
    });
    clearConversation(db, onlyHidden.conversationId, '2026-11-19T09:08:00.000Z');

    const file = await exportFile(server, WITH);

    expect(file).toContain('A reply from Claude about the prediction.');
    expect(file).not.toContain('Sent before Start over.');
    expect(file).not.toContain('A reply the owner hid.');
    expect(file).not.toContain('Sent from lesson 3.');
    expect(section(file, 'ACT-3-ONLY', 3)).not.toContain('AI feedback');
  });

  it('does not carry the conversation of an activity the release dropped (EX8)', async () => {
    const gone = {
      activity_id: 'ACT-1-GONE',
      lesson_id: 'FIX-LS-01',
      title: 'Withdrawn practice',
      kind: 'kind-withdrawn',
      source_heading: 'Practice W heading',
      response_fields: ['prediction'],
    };
    const before = app(release({ activities: [...STANDARD_ACTIVITIES, gone] }));
    await saveAll(before, 'ACT-1-GONE', 'prediction', ['Dropped answer.']);
    const { conversationId } = startConversation(db, {
      activityId: 'ACT-1-GONE',
      sessionId: 'session-gone',
      sentFields: [{ fieldName: 'prediction', text: 'Dropped answer.' }],
      provenance: lesson1,
      at: '2026-11-19T09:50:00.000Z',
    });
    appendTurn(db, conversationId, {
      role: 'claude',
      text: 'A reply about a dropped activity.',
      model: 'claude-sonnet-5-5',
      outcome: 'complete',
      provenance: lesson1,
      at: '2026-11-19T09:50:10.000Z',
    });

    const file = await exportFile(app(), WITH);

    expect(file).toContain('Work this release no longer shows');
    expect(file).not.toContain('A reply about a dropped activity.');
  });
});
