/**
 * EC10–EC12 in docs/specs/earlier-conversations.md: `conversations=all` carries the conversations
 * Start over hid, and `0` and `1` still do not.
 *
 * Conversations are arranged straight into the store, as in exportConversations.test.ts: what is
 * under test is what the export reads. Each absence is checked against the same store exported
 * with `all`, so an export that never writes an earlier conversation cannot pass it.
 */

const dirs: string[] = [];
let db: Db;

beforeEach(() => {
  db = openDatabase(':memory:');
  vi.useFakeTimers({ toFake: ['Date'] });
  vi.setSystemTime(new Date('2026-11-19T12:00:00.000Z'));
});

afterEach(() => {
  vi.useRealTimers();
  db.close();
  while (dirs.length > 0) removeDir(dirs.pop() as string);
});

function release(options: Parameters<typeof writeExportRelease>[0] = {}): string {
  const dir = writeExportRelease(options);
  dirs.push(dir);
  return dir;
}

function app(dir = release()) {
  return exportApp(db, [{ id: 'FIX', dir }]);
}

const ALL = { ...WHOLE_COURSE, conversations: 'all' };
const CURRENT = { ...WHOLE_COURSE, conversations: '1' };
const CURRENT_LABEL = 'AI feedback (generated by Claude, not a review by the author)';

function earlierHeading(startedAt: string, clearedAt: string): string {
  return `#### AI feedback, earlier conversation started ${startedAt}, started over ${clearedAt} (generated by Claude, not a review by the author)`;
}

const lesson1: TurnProvenance = {
  candidateLessonId: 'FIX-LS-01',
  contentVersion: '1.0.0-draft',
  releaseId: 'FIX-RELEASE',
};
const lesson3: TurnProvenance = { ...lesson1, candidateLessonId: LESSON_3 };

/**
 * One conversation on `activityId`: the first question at `at`, then a Claude turn ten seconds
 * later that either finished with `reply` or failed. Cleared at `clearedAt` when given.
 */
function conversation(input: {
  readonly activityId: string;
  readonly sent: string;
  readonly reply: string | null;
  readonly at: string;
  readonly clearedAt?: string;
  readonly provenance?: TurnProvenance;
  readonly model?: string;
}): number {
  const provenance = input.provenance ?? lesson1;
  const { conversationId } = startConversation(db, {
    activityId: input.activityId,
    sessionId: `session-${input.sent}`,
    sentFields: [{ fieldName: 'prediction', text: input.sent }],
    provenance,
    at: input.at,
  });
  const replyAt = new Date(Date.parse(input.at) + 10_000).toISOString();
  appendTurn(
    db,
    conversationId,
    input.reply === null
      ? {
          role: 'claude',
          text: '',
          model: null,
          outcome: 'failed',
          failure: 'Claude did not finish within 3 minutes.',
          provenance,
          at: replyAt,
        }
      : {
          role: 'claude',
          text: input.reply,
          model: input.model ?? 'claude-sonnet-5-5',
          outcome: 'complete',
          provenance,
          at: replyAt,
        },
  );
  if (input.clearedAt) clearConversation(db, conversationId, input.clearedAt);
  return conversationId;
}

/** On ACT-1-ZULU: two earlier conversations, cleared in the opposite order to their start, and a current one. */
function zuluHistory(): void {
  conversation({
    activityId: 'ACT-1-ZULU',
    sent: 'Oldest attempt.',
    reply: 'Reply to the oldest attempt.',
    at: '2026-11-19T09:00:00.000Z',
    clearedAt: '2026-11-19T09:50:00.000Z',
  });
  conversation({
    activityId: 'ACT-1-ZULU',
    sent: 'Middle attempt.',
    reply: 'Reply to the middle attempt.',
    at: '2026-11-19T09:10:00.000Z',
    clearedAt: '2026-11-19T09:20:00.000Z',
  });
  conversation({
    activityId: 'ACT-1-ZULU',
    sent: 'Current attempt.',
    reply: 'Reply to the current attempt.',
    at: '2026-11-19T10:00:00.000Z',
  });
}

describe('the conversations parameter (EC10)', () => {
  it('accepts all', async () => {
    const answer = await app().inject({ method: 'GET', url: exportUrl(ALL) });
    expect(answer.statusCode).toBe(200);
  });

  it.each([
    ['ALL', 'ALL'],
    ['every', 'every'],
    ['empty', ''],
  ])('refuses %s, naming the parameter', async (_, value) => {
    const answer = await app().inject({
      method: 'GET',
      url: exportUrl({ ...WHOLE_COURSE, conversations: value }),
    });
    expect(answer.statusCode).toBe(400);
    expect(answer.json().message).toContain('`conversations`');
  });

  it('refuses all given twice', async () => {
    const answer = await app().inject({
      method: 'GET',
      url: exportUrl({ ...WHOLE_COURSE, conversations: ['all', 'all'] }),
    });
    expect(answer.statusCode).toBe(400);
    expect(answer.json().message).toContain('`conversations`');
  });
});

describe('with earlier conversations (EC11)', () => {
  it('puts the current conversation first, then each earlier one under its own heading, newest first', async () => {
    const server = app();
    zuluHistory();

    const file = await exportFile(server, ALL);

    const zulu = section(file, 'ACT-1-ZULU', 3);
    const headings = linesOutsideFences(zulu).filter((line) => line.startsWith('#### '));
    expect(headings).toEqual([
      '#### Your prediction',
      '#### What you observed',
      `#### ${CURRENT_LABEL}`,
      earlierHeading('2026-11-19T09:00:00.000Z', '2026-11-19T09:50:00.000Z'),
      earlierHeading('2026-11-19T09:10:00.000Z', '2026-11-19T09:20:00.000Z'),
    ]);
  });

  it('writes each earlier conversation’s turns under its own heading, as EX10 writes turns', async () => {
    const server = app();
    zuluHistory();

    const file = await exportFile(server, ALL);

    const middle = section(
      file,
      earlierHeading('2026-11-19T09:10:00.000Z', '2026-11-19T09:20:00.000Z').slice(5),
      4,
    );
    expect(linesOutsideFences(middle)).toContain('Turn 1 · You · 2026-11-19T09:10:00.000Z');
    expect(middle).toContain('Middle attempt.');
    expect(middle).toContain('Reply to the middle attempt.');
    expect(middle).not.toContain('Oldest attempt.');
    expect(blockWith(file, 'Reply to the middle attempt.').description).toBe(
      'Turn 2 · Claude · claude-sonnet-5-5 · 2026-11-19T09:10:10.000Z',
    );
    expect(blockWith(file, 'Middle attempt.').description).toContain('Your prediction');
  });

  it('puts the later conversation first when two were started over at the same moment', async () => {
    const server = app();
    conversation({
      activityId: 'ACT-1-ZULU',
      sent: 'Started first.',
      reply: 'Reply to the first.',
      at: '2026-11-19T09:00:00.000Z',
      clearedAt: '2026-11-19T09:30:00.000Z',
    });
    conversation({
      activityId: 'ACT-1-ZULU',
      sent: 'Started second.',
      reply: 'Reply to the second.',
      at: '2026-11-19T09:10:00.000Z',
      clearedAt: '2026-11-19T09:30:00.000Z',
    });

    const file = await exportFile(server, ALL);

    const headings = linesOutsideFences(section(file, 'ACT-1-ZULU', 3)).filter((line) =>
      line.startsWith('#### AI'),
    );
    expect(headings).toEqual([
      earlierHeading('2026-11-19T09:10:00.000Z', '2026-11-19T09:30:00.000Z'),
      earlierHeading('2026-11-19T09:00:00.000Z', '2026-11-19T09:30:00.000Z'),
    ]);
  });

  it('writes an earlier conversation’s failed turn with its failure and the text that had arrived', async () => {
    const server = app();
    const id = conversation({
      activityId: 'ACT-1-ZULU',
      sent: 'Asked before a failed follow-up.',
      reply: 'A finished earlier reply.',
      at: '2026-11-19T09:00:00.000Z',
    });
    appendTurn(db, id, {
      role: 'learner',
      text: 'An earlier follow-up.',
      provenance: lesson1,
      at: '2026-11-19T09:01:00.000Z',
    });
    appendTurn(db, id, {
      role: 'claude',
      text: 'Partial earlier reply',
      model: null,
      outcome: 'failed',
      failure: 'Claude Code stopped mid-reply.',
      provenance: lesson1,
      at: '2026-11-19T09:01:30.000Z',
    });
    clearConversation(db, id, '2026-11-19T09:05:00.000Z');

    const file = await exportFile(server, ALL);

    const earlierSection = section(
      file,
      earlierHeading('2026-11-19T09:00:00.000Z', '2026-11-19T09:05:00.000Z').slice(5),
      4,
    );
    expect(earlierSection).toContain('Partial earlier reply');
    expect(blockWith(file, 'Partial earlier reply').description).toBe(
      'Turn 4 · Claude · model not reported · 2026-11-19T09:01:30.000Z · Failed: Claude Code stopped mid-reply.',
    );
  });

  it('shows the earlier conversations of an activity that has no current one', async () => {
    const server = app();
    conversation({
      activityId: 'ACT-3-ONLY',
      sent: 'Lesson 3 attempt.',
      reply: 'Reply in lesson 3.',
      at: '2026-11-19T09:30:00.000Z',
      clearedAt: '2026-11-19T09:40:00.000Z',
      provenance: lesson3,
    });

    const file = await exportFile(server, ALL);

    const only = section(file, 'ACT-3-ONLY', 3);
    const headings = linesOutsideFences(only).filter((line) => line.startsWith('#### AI'));
    expect(headings).toEqual([
      earlierHeading('2026-11-19T09:30:00.000Z', '2026-11-19T09:40:00.000Z'),
    ]);
    expect(only).toContain('Reply in lesson 3.');
  });

  it('leaves out a hidden conversation that never got a reply', async () => {
    const server = app();
    conversation({
      activityId: 'ACT-1-ZULU',
      sent: 'Asked, then Try again.',
      reply: null,
      at: '2026-11-19T09:00:00.000Z',
      clearedAt: '2026-11-19T09:01:00.000Z',
    });
    conversation({
      activityId: 'ACT-1-ZULU',
      sent: 'Answered, then Start over.',
      reply: 'A reply that was started over.',
      at: '2026-11-19T09:02:00.000Z',
      clearedAt: '2026-11-19T09:03:00.000Z',
    });

    const file = await exportFile(server, ALL);

    expect(file).toContain('A reply that was started over.');
    expect(file).not.toContain('Asked, then Try again.');
    expect(file).not.toContain('Claude did not finish within 3 minutes.');
  });

  it('still does not carry the conversations of an activity the release dropped', async () => {
    const gone = {
      activity_id: 'ACT-1-GONE',
      lesson_id: 'FIX-LS-01',
      title: 'Withdrawn practice',
      kind: 'kind-withdrawn',
      source_heading: 'Practice W heading',
      response_fields: ['prediction'],
    };
    const before = app(release({ activities: [...STANDARD_ACTIVITIES, gone] }));
    await saveAll(before, 'ACT-1-GONE', 'prediction', ['Dropped answer.']);
    conversation({
      activityId: 'ACT-1-GONE',
      sent: 'Asked on a dropped activity.',
      reply: 'An earlier reply on a dropped activity.',
      at: '2026-11-19T09:00:00.000Z',
      clearedAt: '2026-11-19T09:05:00.000Z',
    });

    const file = await exportFile(app(), ALL);

    expect(file).toContain('Work this release no longer shows');
    expect(file).not.toContain('An earlier reply on a dropped activity.');
  });
});

describe('the context line, and 0 and 1 unchanged (EC12)', () => {
  it('says earlier conversations are included only for all', async () => {
    const server = app();

    expect(contextLine(await exportFile(server, ALL), 'AI feedback conversations')).toBe(
      'AI feedback conversations: included, with earlier conversations',
    );
    expect(contextLine(await exportFile(server, CURRENT), 'AI feedback conversations')).toBe(
      'AI feedback conversations: included',
    );
  });

  it('carries no earlier conversation’s text, failure or model with 0 or 1', async () => {
    const server = app();
    zuluHistory();
    const earlierTexts = [
      'Oldest attempt.',
      'Reply to the oldest attempt.',
      'Middle attempt.',
      'Reply to the middle attempt.',
      'earlier conversation',
    ];

    const all = await exportFile(server, ALL);
    const current = await exportFile(server, CURRENT);
    const none = await exportFile(server, { ...WHOLE_COURSE, conversations: '0' });

    for (const text of earlierTexts) expect(all, text).toContain(text);
    expect(current).toContain('Reply to the current attempt.');
    for (const file of [current, none]) {
      for (const text of earlierTexts) expect(file, text).not.toContain(text);
    }
  });

  it('carries no earlier conversation’s model or failure with 0 or 1', async () => {
    const server = app();
    const id = conversation({
      activityId: 'ACT-1-ZULU',
      sent: 'Asked with a distinct model.',
      reply: 'Answered by a distinct model.',
      at: '2026-11-19T09:00:00.000Z',
      model: 'claude-model-only-in-an-earlier-conversation',
    });
    appendTurn(db, id, {
      role: 'learner',
      text: 'Then a follow-up.',
      provenance: lesson1,
      at: '2026-11-19T09:01:00.000Z',
    });
    appendTurn(db, id, {
      role: 'claude',
      text: '',
      model: null,
      outcome: 'failed',
      failure: 'A failure only an earlier conversation has.',
      provenance: lesson1,
      at: '2026-11-19T09:01:30.000Z',
    });
    clearConversation(db, id, '2026-11-19T09:05:00.000Z');
    const marks = [
      'claude-model-only-in-an-earlier-conversation',
      'A failure only an earlier conversation has.',
    ];

    const all = await exportFile(server, ALL);
    const current = await exportFile(server, CURRENT);
    const none = await exportFile(server, { ...WHOLE_COURSE, conversations: '0' });

    for (const mark of marks) expect(all, mark).toContain(mark);
    for (const file of [current, none]) {
      for (const mark of marks) expect(file, mark).not.toContain(mark);
    }
  });
});
