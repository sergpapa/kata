/**
 * Criteria A6, A7, A8 and A12 in docs/specs/release-additions.md: what a build that adds still
 * refuses, and how the command line reports an addition.
 */
import fs from 'node:fs';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { runCli } from './cli.js';
import { readZip } from './zip.js';
import {
  LESSON_5,
  NEW_KIT,
  NEW_KIT_FOLDER,
  NEW_KIT_ID,
  NEW_LESSON,
  NEW_LESSON_ID,
  addKit,
  addLesson,
  cleanTemps,
  correctLesson5,
  editReleaseJson,
  lessonFile,
  moveReleaseVersion,
  outputPath,
  seededSource,
  sha256,
} from './testkit/sourceFixture.js';
import { built, expectRefusal, kitZip } from './testkit/buildAssertions.js';

afterEach(cleanTemps);

const NEW_KIT_NAMED = new RegExp(`${NEW_KIT_ID}|${NEW_KIT}`);

describe('removal is still refused (A6)', () => {
  it('refuses a release that leaves out a lesson, naming it', () => {
    const source = seededSource();
    editReleaseJson(source, (release) => {
      release.lessons = release.lessons.filter((name) => name !== LESSON_5);
    });
    moveReleaseVersion(source);
    expectRefusal(source, /LS-M020-05/, /remov/i);
  });

  it('refuses a release that swaps a lesson for a new one, naming the one left out', () => {
    const source = seededSource();
    addLesson(source);
    editReleaseJson(source, (release) => {
      release.lessons = release.lessons.filter((name) => name !== LESSON_5);
    });
    moveReleaseVersion(source);
    expectRefusal(source, /LS-M020-05/, /remov/i);
  });

  it('refuses a release that leaves out a kit, naming it', () => {
    const source = seededSource();
    editReleaseJson(source, (release) => {
      release.labs = release.labs.filter((lab) => lab.lab_id !== 'FSSE-HTTP-LAB-14-15');
    });
    moveReleaseVersion(source);
    expectRefusal(source, /FSSE-HTTP-LAB-14-15/, /remov/i);
  });

  it('refuses a release that swaps a kit for a new one, naming the one left out', () => {
    const source = seededSource();
    editReleaseJson(source, (release) => {
      release.labs = release.labs.filter((lab) => lab.lab_id !== 'FSSE-HTTP-LAB-14-15');
    });
    addKit(source, ['LS-M021-06', 'LS-M021-07']);
    moveReleaseVersion(source);
    expectRefusal(source, /FSSE-HTTP-LAB-14-15/, /remov/i);
  });
});

describe('generated folders never ship (A7)', () => {
  /** A source with Lesson 16 and its kit, whose folder also holds `extra`. */
  function sourceWithKit(extra: Record<string, string>): string {
    const source = seededSource();
    addLesson(source);
    addKit(source, [NEW_LESSON_ID], extra);
    moveReleaseVersion(source);
    return source;
  }

  it('refuses a directory its own .gitignore names, whatever the directory is called', () => {
    const source = sourceWithKit({
      '.gitignore': 'test-results/\n',
      'test-results/run.json': '{}\n',
    });
    expectRefusal(source, NEW_KIT_NAMED, /test-results/);
  });

  it('reads a plain name as well as name/, and skips comments and blank lines', () => {
    const source = sourceWithKit({
      '.gitignore': '# generated by a grading run\n\nresults\n',
      'results/grade-results.json': '{}\n',
    });
    expectRefusal(source, NEW_KIT_NAMED, /results/);
  });

  it('refuses such a directory nested below the kit folder', () => {
    const source = sourceWithKit({
      '.gitignore': 'test-results/\n',
      'site/test-results/run.json': '{}\n',
    });
    expectRefusal(source, NEW_KIT_NAMED, /test-results/);
  });

  it.each([
    ['an anchored /name/', '/test-results/\n', 'test-results/run.json'],
    ['a **/name', '**/coverage\n', 'site/coverage/index.html'],
    ['a name/* line', 'playwright-report/*\n', 'playwright-report/index.html'],
  ])('reads %s line as naming that directory', (_form, gitignore, member) => {
    const source = sourceWithKit({ '.gitignore': gitignore, [member]: 'generated\n' });
    expectRefusal(source, NEW_KIT_NAMED, new RegExp(member.split('/').slice(-2, -1)[0]!));
  });

  it('refuses node_modules at any depth even when no .gitignore names it', () => {
    const source = sourceWithKit({
      'tools/node_modules/some-package/index.js': 'module.exports = 1;\n',
    });
    expectRefusal(source, NEW_KIT_NAMED, /node_modules/);
  });

  it('ships the .gitignore itself when none of the folders it names is present', () => {
    const source = sourceWithKit({ '.gitignore': 'node_modules/\nresults/\n' });
    const out = built(source);
    expect(readZip(kitZip(out)).map((member) => member.path)).toContain(
      `${NEW_KIT_FOLDER}/.gitignore`,
    );
  });

  it('does not interpret a glob line, so a file it would match still ships', () => {
    const source = sourceWithKit({ '.gitignore': '*.log\n', 'run.log': 'one line\n' });
    const out = built(source);
    expect(readZip(kitZip(out)).map((member) => member.path)).toContain(
      `${NEW_KIT_FOLDER}/run.log`,
    );
  });
});

describe('the command line names additions (A8)', () => {
  function run(source: string, out: string): string[] {
    const lines: string[] = [];
    expect(runCli(['build', source, out], (line) => lines.push(line))).toBe(0);
    return lines;
  }

  it('prints each added lesson and kit with its version and hash, marked as added', () => {
    const source = seededSource();
    addLesson(source);
    addKit(source, [NEW_LESSON_ID]);
    moveReleaseVersion(source);
    const out = outputPath();
    const lines = run(source, out);

    const lessonLine = lines.find((line) => line.includes(NEW_LESSON_ID));
    expect(lessonLine).toMatch(/added/i);
    expect(lessonLine).toContain('1.0.0-draft');
    expect(lessonLine).toContain(
      sha256(fs.readFileSync(path.join(out, 'content/lessons', NEW_LESSON))).slice(0, 8),
    );
    const kitLine = lines.find((line) => line.includes(NEW_KIT_ID));
    expect(kitLine).toMatch(/added/i);
    expect(kitLine).toContain('1.0.0-draft');
    expect(kitLine).toContain(sha256(kitZip(out)).slice(0, 8));
    expect(lines.join('\n')).toMatch(/\b20 lessons and kits unchanged/);
  });

  it('prints changed and added entries side by side', () => {
    const source = seededSource();
    correctLesson5(source);
    addLesson(source);
    moveReleaseVersion(source);
    const lines = run(source, outputPath());

    expect(lines.find((line) => line.includes('LS-M020-05'))).toMatch(
      /1\.0\.0-draft.*1\.0\.1-draft/,
    );
    expect(lines.find((line) => line.includes(NEW_LESSON_ID))).toMatch(/added/i);
    expect(lines.join('\n')).toMatch(/\b18 lessons and kits unchanged/);
  });
});

describe('a malformed addition is refused by name (A12)', () => {
  it('refuses a listed lesson file that is missing', () => {
    const source = seededSource();
    addLesson(source);
    fs.rmSync(lessonFile(source, NEW_LESSON));
    moveReleaseVersion(source);
    expectRefusal(source, new RegExp(NEW_LESSON.replace(/\./g, '\\.')));
  });

  it('refuses two lessons with one lesson ID', () => {
    const source = seededSource();
    addLesson(source);
    fs.copyFileSync(lessonFile(source, NEW_LESSON), lessonFile(source, 'Lesson_16_copy.md'));
    editReleaseJson(source, (release) => {
      release.lessons.push('Lesson_16_copy.md');
    });
    moveReleaseVersion(source);
    expectRefusal(source, new RegExp(NEW_LESSON_ID));
  });

  it('refuses an added kit whose source folder is missing', () => {
    const source = seededSource();
    addLesson(source);
    addKit(source, [NEW_LESSON_ID]);
    fs.rmSync(path.join(source, 'labs', NEW_KIT), { recursive: true });
    moveReleaseVersion(source);
    expectRefusal(source, NEW_KIT_NAMED);
  });

  it.each([
    ['lab_id', { lab_id: 'FSSE-HTTP-LAB-99' }, 'lab'],
    ['kit_id', { kit_id: 'FSSE-HTTP-LAB-99' }, 'kit'],
  ] as const)(
    'refuses a kit manifest whose %s differs from release.json',
    (_field, manifest, shape) => {
      const source = seededSource();
      addLesson(source);
      addKit(source, [NEW_LESSON_ID], {}, { shape, manifest });
      moveReleaseVersion(source);
      expectRefusal(source, NEW_KIT_NAMED, /FSSE-HTTP-LAB-99/);
    },
  );

  it.each([
    ['null', null],
    ['a number', 16],
  ])('refuses a kit manifest whose lab_id is %s', (_what, value) => {
    const source = seededSource();
    addLesson(source);
    addKit(source, [NEW_LESSON_ID], {}, { manifest: { lab_id: value } });
    moveReleaseVersion(source);
    expectRefusal(source, NEW_KIT_NAMED, /lab_id/);
  });

  it('refuses a kit that lists one lesson twice', () => {
    const source = seededSource();
    addLesson(source);
    addKit(source, [NEW_LESSON_ID]);
    editReleaseJson(source, (release) => {
      release.labs[release.labs.length - 1]!.lesson_ids = [NEW_LESSON_ID, NEW_LESSON_ID];
    });
    moveReleaseVersion(source);
    expectRefusal(source, NEW_KIT_NAMED, new RegExp(NEW_LESSON_ID));
  });

  it('refuses two archive names that differ only in letter case', () => {
    const source = seededSource();
    addLesson(source);
    addKit(source, [NEW_LESSON_ID]);
    editReleaseJson(source, (release) => {
      release.labs[release.labs.length - 1]!.archive = 'http_lesson_02_local_server_kit_v1.ZIP';
    });
    moveReleaseVersion(source);
    expectRefusal(source, /http_lesson_02_local_server_kit_v1/i, /archive/);
  });

  it('refuses a kit serving a lesson the release does not list', () => {
    const source = seededSource();
    addKit(source, ['LS-M099-01']);
    moveReleaseVersion(source);
    expectRefusal(source, NEW_KIT_NAMED, /LS-M099-01/);
  });

  it('refuses a kit manifest with no version', () => {
    const source = seededSource();
    addLesson(source);
    addKit(source, [NEW_LESSON_ID], {}, { manifest: { version: undefined } });
    moveReleaseVersion(source);
    expectRefusal(source, NEW_KIT_NAMED, /version/);
  });

  it.each([
    [
      'lab_id',
      (lab: { lab_id: string; archive: string }) => ({ ...lab, lab_id: 'FSSE-HTTP-LAB-02' }),
    ],
    [
      'archive',
      (lab: { lab_id: string; archive: string }) => ({
        ...lab,
        archive: 'HTTP_Lesson_02_Local_Server_Kit_v1.zip',
      }),
    ],
  ])('refuses two kits sharing a %s', (field, alter) => {
    const source = seededSource();
    addLesson(source);
    addKit(
      source,
      [NEW_LESSON_ID],
      {},
      field === 'lab_id' ? { manifest: { lab_id: 'FSSE-HTTP-LAB-02' } } : {},
    );
    editReleaseJson(source, (release) => {
      const last = release.labs.length - 1;
      release.labs[last] = { ...alter(release.labs[last]!), lesson_ids: [NEW_LESSON_ID] };
    });
    moveReleaseVersion(source);
    const named = field === 'lab_id' ? /FSSE-HTTP-LAB-02/ : /HTTP_Lesson_02_Local_Server_Kit_v1/;
    expectRefusal(source, named, new RegExp(`${field}|twice|more than one`, 'i'));
  });
});
