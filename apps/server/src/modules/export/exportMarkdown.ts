import { fieldLabel } from '../learner/fieldLabels.js';
import type { FeedbackTurnForPage } from '../feedback/types.js';
import type { StoredResponse, StoredRevision } from '../learner/responseRepository.js';
import type {
  DroppedActivity,
  ExportContent,
  ExportedActivity,
  ExportedField,
  ExportedLesson,
} from './exportData.js';

/**
 * The export file, written from what `readExport` read (docs/specs/export.md, ADR 0020).
 *
 * The shape is a contract with its reader: context before the first `## `; a lesson per `## `, an
 * activity per `### `, a field per `#### `; and every text anybody wrote in a fence, with the one
 * line above that fence saying which version, which release and when (EX6). Nothing here reads the
 * store or the clock, so the same content always makes the same file.
 */

export const CONVERSATION_HEADING = 'AI feedback (generated by Claude, not a review by the author)';
export const DROPPED_HEADING = 'Work this release no longer shows';

/**
 * A value that must stay on its own line — a heading, a labelled line, a turn line. A failure is an
 * error message and can run over several lines; unflattened, a line of it starting `## ` or three
 * backticks would restructure everything after it (EX10).
 */
function oneLine(value: string): string {
  return value.replace(/\s*[\r\n]+\s*/g, ' ');
}

/** A lesson order as the file and its name write it: two digits, so 09 sorts before 10. */
export function twoDigits(order: number): string {
  return String(order).padStart(2, '0');
}

/**
 * A backtick fence one longer than the longest backtick run in the text, and never shorter than
 * three, so nothing the owner or Claude wrote can close it early (EX7).
 */
function fenced(text: string): string {
  const longest = Math.max(0, ...(text.match(/`+/g) ?? []).map((run) => run.length));
  const fence = '`'.repeat(Math.max(3, longest + 1));
  return `${fence}text\n${text}\n${fence}`;
}

/** A description line, then its block: the pair EX6 makes the reader's unit. */
function described(description: string, text: string): string {
  return `${description}\n\n${fenced(text)}`;
}

function against(stamp: { contentVersion: string; releaseId: string }): string {
  return `content version ${stamp.contentVersion} of release ${stamp.releaseId}`;
}

function currentAnswer(current: StoredResponse): string {
  const when = `${current.updatedAt} against ${against(current)} (revision ${current.revision})`;
  if (current.text === '') return `Emptied: saved empty at ${when}.`;
  return described(`Current answer, saved ${when}:`, current.text);
}

function earlierVersion(revision: StoredRevision): string {
  const description = `Earlier version, revision ${revision.revision}, written ${revision.writtenAt} against ${against(revision)}:`;
  // An earlier revision can itself have been an emptied box; it is said, not fenced as nothing.
  return revision.text === ''
    ? description.replace(/:$/, ': empty.')
    : described(description, revision.text);
}

function field(exported: ExportedField): string {
  const parts = [`#### ${fieldLabel(exported.fieldName)}`];
  parts.push(exported.current ? currentAnswer(exported.current) : 'No answer recorded.');
  parts.push(...exported.earlier.map(earlierVersion));
  return parts.join('\n\n');
}

function turn(one: FeedbackTurnForPage): string {
  if (one.role === 'learner') {
    const line = `Turn ${one.turn} · You · ${one.writtenAt}`;
    const parts = [one.text === '' ? line : described(line, one.text)];
    for (const sent of one.sentFields ?? []) {
      parts.push(described(`${fieldLabel(sent.fieldName)}, as sent:`, sent.text));
    }
    return parts.join('\n\n');
  }
  const failed =
    one.outcome === 'failed' ? ` · Failed: ${oneLine(one.failure ?? 'no reason was stored')}` : '';
  const line = `Turn ${one.turn} · Claude · ${oneLine(one.model ?? 'model not reported')} · ${one.writtenAt}${failed}`;
  return one.text === '' ? line : described(line, one.text);
}

function activity(exported: ExportedActivity): string {
  const { activity: identity } = exported;
  const parts = [
    `### ${oneLine(identity.title)}`,
    [
      `- Activity id: ${identity.activityId}`,
      `- Kind: ${oneLine(identity.kind)}`,
      `- Source heading: ${oneLine(identity.sourceHeading)}`,
    ].join('\n'),
    ...exported.fields.map(field),
  ];
  if (exported.turns) {
    parts.push(`#### ${CONVERSATION_HEADING}`, ...exported.turns.map(turn));
  }
  return parts.join('\n\n');
}

function lesson(exported: ExportedLesson): string {
  const { lesson: identity } = exported;
  const parts = [
    `## ${oneLine(identity.displayTitle)}`,
    [
      `- Order: ${twoDigits(identity.order)}`,
      `- Lesson id: ${identity.candidateLessonId}`,
      `- Content version: ${identity.contentVersion}`,
      `- Document id: ${identity.documentId}`,
    ].join('\n'),
  ];
  if (exported.activities.length === 0) parts.push('This lesson has no recording activities.');
  parts.push(...exported.activities.map(activity));
  return parts.join('\n\n');
}

function droppedActivity(exported: DroppedActivity): string {
  return [
    `### ${exported.activityId}`,
    `- Activity id: ${exported.activityId}\n- Lesson id: ${exported.candidateLessonId}`,
    ...exported.fields.map(field),
  ].join('\n\n');
}

/**
 * The whole file. Pure: the time and the app version come in with `context`, so the same content
 * and context always make the same bytes.
 */
export function exportMarkdown(
  content: ExportContent,
  context: {
    readonly courseId: string;
    readonly courseTitle: string;
    readonly appVersion: string;
    readonly exportedAt: string;
  },
): string {
  const { release, from, to } = content;
  const sections = [
    `# EduCode export: ${oneLine(context.courseTitle)}`,
    [
      `- Course: ${context.courseId} — ${oneLine(context.courseTitle)}`,
      `- Release: ${release.releaseId} version ${release.version} (${release.date ?? 'undated'})`,
      `- App version: ${context.appVersion}`,
      `- Exported: ${context.exportedAt}`,
      `- Lessons: ${twoDigits(from.order)} ${oneLine(from.displayTitle)} to ${twoDigits(to.order)} ${oneLine(to.displayTitle)}`,
      `- AI feedback conversations: ${content.conversations ? 'included' : 'not included'}`,
    ].join('\n'),
    'Only work the app acknowledged as saved is included. Each text sits in a fenced block; the ' +
      'line above it says when it was written and which content version and release it answered.',
    ...content.lessons.map(lesson),
  ];
  if (content.dropped.length > 0) {
    sections.push(
      `## ${DROPPED_HEADING}`,
      'These answers belong to activities the current release no longer lists. They are kept as ' +
        'they were saved, under the lesson they were last saved against.',
      ...content.dropped.map(droppedActivity),
    );
  }
  return `${sections.join('\n\n')}\n`;
}
